/**
 * Resolves the production DBX Workbench ES-module graph the way DBX v0.6.23
 * serves plugin UI assets.
 *
 * DBX serves UI files from the declared `entrypoints.ui.root` ("ui") as
 * `<origin>/<plugin-id>/<ui-relative-path>`, so the URL space of the sandboxed
 * Workbench is rooted at the ui directory. The host inlines the entry HTML's
 * scripts/styles and injects the plugin asset origin as `<base>`; runtime
 * module fetches then resolve against that URL space, not against the package
 * root. That means:
 *
 *  - a specifier like `../src/x.mjs` from `ui/generation-workbench/app.mjs`
 *    resolves to `<plugin-id>/src/x.mjs`, which the asset protocol maps to
 *    `ui/src/x.mjs` — the file must be vendored there by the build;
 *  - `node:` builtins and `Buffer` are unavailable in the WebView, so any
 *    reachable module that uses them fails to load.
 *
 * `collectUiRuntimeGraph` walks the real module graph from `ui/app.mjs` (both
 * static and dynamic imports), maps every resolved URL back to a package path,
 * and rejects Node-only modules. Both the build and the package contract test
 * use it, so the packaged graph and the asserted graph cannot drift.
 */
import path from "node:path";

const posix = path.posix;

export const UI_ENTRY = "ui/app.mjs";
const UI_PREFIX = "ui/";

/**
 * Package paths generated by the build (no matching source file) and the
 * source file the build must read for them.
 */
export const UI_SOURCE_ALIASES = new Map([
  ["ui/schema-metadata-probe.mjs", "src/host/dbx-schema-metadata-probe.mjs"],
]);

/** Remove comments so import scanning cannot match JSDoc `import("...")` types. @param {string} source */
export function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|[^:])\/\/[^\n]*/g, "$1");
}

/** Runtime import/export specifiers, including dynamic `import()`. @param {string} source */
export function runtimeImportSpecifiers(source) {
  const clean = stripComments(source);
  const specifiers = new Set();
  for (const match of clean.matchAll(/\bimport\s+(?:[^"']*?\s+from\s+)?["']([^"']+)["']/g)) specifiers.add(match[1]);
  for (const match of clean.matchAll(/\bexport\s+[^"']*?\s+from\s+["']([^"']+)["']/g)) specifiers.add(match[1]);
  for (const match of clean.matchAll(/\bimport\s*\(\s*["']([^"']+)["']\s*\)/g)) specifiers.add(match[1]);
  return [...specifiers];
}

/** @param {string} packagePath */
function sourcePathFor(packagePath) {
  if (packagePath.startsWith(`${UI_PREFIX}src/`)) return packagePath.slice(UI_PREFIX.length);
  return UI_SOURCE_ALIASES.get(packagePath) ?? packagePath;
}

/** @param {string} packagePath @param {string} specifier @returns {string} resolved package path */
function resolveUiImport(packagePath, specifier) {
  if (!specifier.startsWith("./") && !specifier.startsWith("../")) {
    if (specifier.startsWith("node:")) {
      throw new Error(`DBX Workbench module '${packagePath}' imports Node builtin '${specifier}'; the sandboxed WebView has no Node runtime`);
    }
    throw new Error(`DBX Workbench module '${packagePath}' imports unsupported bare specifier '${specifier}'`);
  }
  const uiRelative = packagePath.startsWith(UI_PREFIX) ? packagePath.slice(UI_PREFIX.length) : packagePath;
  const resolved = posix.normalize(posix.join(posix.dirname(uiRelative), specifier));
  if (resolved.startsWith("..") || posix.isAbsolute(resolved)) {
    throw new Error(`DBX Workbench module '${packagePath}' escapes the ui root with '${specifier}'`);
  }
  const nextPackagePath = `${UI_PREFIX}${resolved}`;
  return nextPackagePath;
}

/**
 * Walk every runtime module reachable from the entry.
 * @param {(sourcePath: string) => Promise<string>} readSource
 * @returns {Promise<Map<string, { sourcePath: string, source: string }>>} keyed by package path
 */
export async function collectUiRuntimeGraph(readSource) {
  const graph = new Map();
  const queue = [UI_ENTRY];
  while (queue.length > 0) {
    const packagePath = queue.shift();
    if (graph.has(packagePath)) continue;
    const sourcePath = sourcePathFor(packagePath);
    const source = await readSource(sourcePath);
    if (/\bBuffer\s*\./.test(stripComments(source))) {
      throw new Error(`DBX Workbench module '${packagePath}' uses Node's Buffer; the sandboxed WebView has no Buffer global`);
    }
    graph.set(packagePath, { sourcePath, source });
    for (const specifier of runtimeImportSpecifiers(source)) {
      const nextPackagePath = resolveUiImport(packagePath, specifier);
      if (!graph.has(nextPackagePath) && !queue.includes(nextPackagePath)) queue.push(nextPackagePath);
    }
  }
  return graph;
}
